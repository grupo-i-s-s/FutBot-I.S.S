BEGIN;

CREATE TABLE planned_substitutions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    club_id INTEGER NOT NULL REFERENCES clubs(id),
    pause_index INTEGER NOT NULL,
    command_id TEXT NOT NULL,
    out_player_id INTEGER NOT NULL REFERENCES players(id),
    in_player_id INTEGER NOT NULL REFERENCES players(id),
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT ck_substitution_pause CHECK (pause_index BETWEEN 1 AND 3),
    CONSTRAINT uq_substitution_command UNIQUE (match_id, club_id, command_id)
);

CREATE UNIQUE INDEX uq_pending_substitution
    ON planned_substitutions(match_id, club_id, pause_index)
    WHERE status = 'PENDING';

COMMIT;
