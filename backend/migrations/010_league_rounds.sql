BEGIN;

ALTER TABLE leagues
    ADD COLUMN draw_seed BIGINT;

CREATE TABLE league_rounds
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    league_id INTEGER NOT NULL
        REFERENCES leagues (id) ON DELETE CASCADE,

    number INTEGER NOT NULL,

    scheduled_at TIMESTAMPTZ NOT NULL,

    bye_club_id INTEGER
        REFERENCES clubs (id),

    CONSTRAINT uq_league_rounds_league_number
        UNIQUE (league_id, number)
);

ALTER TABLE matches
    ADD COLUMN league_round_id INTEGER
        REFERENCES league_rounds (id) ON DELETE CASCADE;

CREATE INDEX ix_matches_league_round_id
    ON matches (league_round_id);

COMMIT;